#!/usr/bin/env python3
"""Generate the C++ punctuation contract from policy.json."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SPEC = json.loads((ROOT / "policy.json").read_text(encoding="utf-8"))
simple = SPEC["simple"]
alternating = SPEC["alternating"]
nested = SPEC["nested"]
styles = SPEC["styles"]
corner_quotes = styles["cornerQuotes"]
hollow_brackets = styles["hollowBrackets"]
enumeration_comma = SPEC["enumerationComma"]
inputs = [entry["input"] for entry in simple + alternating] + [nested["openingInput"], nested["closingInput"]]
if (SPEC["contractVersion"] != 4 or any(len(value) != 1 or not 32 <= ord(value) < 127 for value in inputs) or
        len(set(inputs)) != len(inputs)):
    raise SystemExit("Invalid punctuation contract")
# 样式是同一个键的另一组字，不是新键：直角引号只能替换交替引号的键，空心括号只能替换 simple 里的键，各键至多出现一次。
alternating_inputs = [entry["input"] for entry in alternating]
simple_inputs = [entry["input"] for entry in simple]
corner_inputs = [entry["input"] for entry in corner_quotes]
hollow_inputs = [entry["input"] for entry in hollow_brackets]
if (sorted(corner_inputs) != sorted(alternating_inputs) or any(value not in simple_inputs for value in hollow_inputs) or
        len(set(hollow_inputs)) != len(hollow_inputs)):
    raise SystemExit("Invalid punctuation contract styles")
# enumerationComma 是「可被偏好关掉的顿号键」：键可以来自 simple（`\`，偏好把它从无条件映射里摘掉），也可以是新键（`/`，不在 is_supported 里）；交替引号和嵌套书名号是状态机，不属于它。
enumeration_inputs = [entry["input"] for entry in enumeration_comma]
if (len(enumeration_comma) != 2 or len(set(enumeration_inputs)) != len(enumeration_inputs) or
        any(len(value) != 1 or not 32 <= ord(value) < 127 for value in enumeration_inputs) or
        any(value in alternating_inputs or value in (nested["openingInput"], nested["closingInput"]) for value in enumeration_inputs) or
        any(entry["output"] != enumeration_comma[0]["output"] for entry in enumeration_comma)):
    raise SystemExit("Invalid punctuation contract enumerationComma")


def char_literal(value):
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"

lines = [
    "// Generated by shared/contracts/punctuation/generate.py; edit policy.json instead.",
    "#pragma once",
    "#include <array>",
    "#include <string_view>",
    "",
    "namespace metasequoia::punctuation_contract",
    "{",
    f"inline constexpr int version = {SPEC['contractVersion']};",
    "struct Mapping",
    "{",
    "    char input;",
    "    const char *output;",
    "};",
    "struct AlternatingMapping",
    "{",
    "    char input;",
    "    const char *opening;",
    "    const char *closing;",
    "};",
    f"inline constexpr std::array<Mapping, {len(simple)}> simple = {{{{",
]
lines += [f"    {{{char_literal(entry['input'])}, {json.dumps(entry['output'], ensure_ascii=False)}}}," for entry in simple]
lines += [
    "}};",
    f"inline constexpr std::array<AlternatingMapping, {len(alternating)}> alternating = {{{{",
]
lines += [
    f"    {{{char_literal(entry['input'])}, {json.dumps(entry['opening'], ensure_ascii=False)}, {json.dumps(entry['closing'], ensure_ascii=False)}}},"
    for entry in alternating
]
lines += [
    "}};",
    f"inline constexpr std::array<AlternatingMapping, {len(corner_quotes)}> corner_quotes = {{{{",
]
lines += [
    f"    {{{char_literal(entry['input'])}, {json.dumps(entry['opening'], ensure_ascii=False)}, {json.dumps(entry['closing'], ensure_ascii=False)}}},"
    for entry in corner_quotes
]
lines += [
    "}};",
    f"inline constexpr std::array<Mapping, {len(hollow_brackets)}> hollow_brackets = {{{{",
]
lines += [f"    {{{char_literal(entry['input'])}, {json.dumps(entry['output'], ensure_ascii=False)}}}," for entry in hollow_brackets]
lines += [
    "}};",
    f"inline constexpr std::array<Mapping, {len(enumeration_comma)}> enumeration_comma = {{{{",
]
lines += [f"    {{{char_literal(entry['input'])}, {json.dumps(entry['output'], ensure_ascii=False)}}}," for entry in enumeration_comma]
lines += [
    "}};",
    f"inline constexpr char nested_opening_input = {char_literal(nested['openingInput'])};",
    f"inline constexpr char nested_closing_input = {char_literal(nested['closingInput'])};",
    f"inline constexpr char nested_opening[] = {json.dumps(nested['opening'], ensure_ascii=False)};",
    f"inline constexpr char nested_opening_inner[] = {json.dumps(nested['nestedOpening'], ensure_ascii=False)};",
    f"inline constexpr char nested_closing[] = {json.dumps(nested['closing'], ensure_ascii=False)};",
    f"inline constexpr char nested_closing_inner[] = {json.dumps(nested['nestedClosing'], ensure_ascii=False)};",
    "constexpr bool is_supported(char input)",
    "{",
    "    for (const auto &mapping : simple)",
    "        if (mapping.input == input) return true;",
    "    for (const auto &mapping : alternating)",
    "        if (mapping.input == input) return true;",
    "    return input == nested_opening_input || input == nested_closing_input;",
    "}",
    "constexpr const char *simple_output(char input)",
    "{",
    "    for (const auto &mapping : simple)",
    "        if (mapping.input == input) return mapping.output;",
    "    return nullptr;",
    "}",
    "constexpr const AlternatingMapping *alternating_mapping(char input)",
    "{",
    "    for (const auto &mapping : alternating)",
    "        if (mapping.input == input) return &mapping;",
    "    return nullptr;",
    "}",
    "constexpr const AlternatingMapping *corner_quote_mapping(char input)",
    "{",
    "    for (const auto &mapping : corner_quotes)",
    "        if (mapping.input == input) return &mapping;",
    "    return nullptr;",
    "}",
    "constexpr const char *hollow_bracket_output(char input)",
    "{",
    "    for (const auto &mapping : hollow_brackets)",
    "        if (mapping.input == input) return mapping.output;",
    "    return nullptr;",
    "}",
    "constexpr const char *enumeration_comma_output(char input)",
    "{",
    "    for (const auto &mapping : enumeration_comma)",
    "        if (mapping.input == input) return mapping.output;",
    "    return nullptr;",
    "}",
    "} // namespace metasequoia::punctuation_contract",
    "",
]
expected = "\n".join(lines)

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
target = ROOT / "policy.h"
if args.check:
    if not target.exists() or target.read_text(encoding="utf-8") != expected:
        raise SystemExit("Punctuation contract header is stale; run shared/contracts/punctuation/generate.py")
else:
    target.write_text(expected, encoding="utf-8")
