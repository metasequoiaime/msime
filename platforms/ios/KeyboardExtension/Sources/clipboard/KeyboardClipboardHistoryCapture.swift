import UIKit

/// 仅在键盘可见且用户明确开启历史时读取；系统后台覆盖的正文无法还原。
@MainActor final class KeyboardClipboardHistoryCapture {
  private let pasteboard: UIPasteboard
  private let center: NotificationCenter
  private let allowed: () -> Bool
  private let save: (Int, String) throws -> Void
  private let buffer = ClipboardHistoryCaptureBuffer()
  private var observer: NSObjectProtocol?
  private var retry: Timer?

  init(pasteboard: UIPasteboard = .general, center: NotificationCenter = .default,
       allowed: @escaping () -> Bool, save: @escaping (Int, String) throws -> Void) {
    self.pasteboard = pasteboard
    self.center = center
    self.allowed = allowed
    self.save = save
  }

  func start() {
    stop()
    buffer.start(changeCount: pasteboard.changeCount)
    observer = center.addObserver(forName: UIPasteboard.changedNotification, object: pasteboard, queue: .main) {
      [weak self] _ in MainActor.assumeIsolated { self?.capture() }
    }
  }

  func stop() {
    if let observer { center.removeObserver(observer) }
    observer = nil
    retry?.invalidate()
    retry = nil
    buffer.stop()
  }

  func discardIfDisallowed() {
    guard observer != nil, !allowed() else { return }
    buffer.start(changeCount: pasteboard.changeCount)
    retry?.invalidate()
    retry = nil
  }

  static func saveToHistory(changeCount: Int, text: String) throws {
    do { try ClipboardHistoryStore().add(text) }
    catch let error as ClipboardHistoryStore.Failure {
      switch error {
      case .empty, .invalidText, .full: return
      default: throw error
      }
    }
    ClipboardCapturePrompt.markCaptured(changeCount: changeCount)
  }

  private func capture() {
    guard observer != nil else { return }
    buffer.capture(changeCount: pasteboard.changeCount, allowed: allowed(), read: {
      // 遵守桌面密码管理器的标准敏感格式；不因自动采集保存一次性或隐藏内容。
      let excluded = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                      "org.nspasteboard.AutoGeneratedType"]
      guard !pasteboard.types.contains(where: excluded.contains), pasteboard.hasStrings else { return nil }
      return pasteboard.string
    }, save: save)
    if buffer.hasPending && retry == nil {
      retry = Timer.scheduledTimer(withTimeInterval: 0.1, repeats: true) { [weak self] _ in
        MainActor.assumeIsolated { self?.capture() }
      }
    } else if !buffer.hasPending {
      retry?.invalidate()
      retry = nil
    }
  }

  deinit {
    if let observer { center.removeObserver(observer) }
    retry?.invalidate()
  }
}
