export function createAiSkinPrompt(): string {
  const scenes = [
    "月光森林里的狐狸茶屋",
    "云朵之间的鲸鱼邮局",
    "雨夜街角的猫咪书店",
    "星际列车上的花园",
    "蘑菇村的秋日集市",
    "珊瑚海里的水母舞会",
    "雪山小屋与极光",
    "竹林里的熊猫茶会",
    "沙漠星空下的旅店",
    "复古街机里的糖果世界",
    "樱花河畔的兔子野餐",
    "漂浮岛屿上的灯塔",
  ];
  const selected = [...scenes]
    .sort(() => Math.random() - 0.5)
    .slice(0, 3)
    .join("；");
  return `这是一次随机皮肤抽卡。分别围绕以下三个灵感创作三套主题，每套对应一个场景：${selected}。自由设计原创角色、插画风格和配色，三套键帽造型与材质都要不同，文字清晰。不要使用已有品牌或角色。`;
}
