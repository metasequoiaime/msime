#!/usr/bin/env python3
"""跑成对偏好夹具 `resources/eval/must-outrank.tsv`：同一串输入下，一个候选必须排在另一个前面，或者某个候选不得出现在首屏。

为什么是成对偏好：词级集只问金标准排第几，量不到「车件 不该压过 车检」这种具体的、有用户反馈的次序；整份基线逐字节比较又说明不了好坏。夹具只断言相对次序，每条带来源，失败就是一条要修的、有出处的问题。

执行走 `convert_eval --dump`（与其他评测同一个二进制、同一套关学习、每例清空上文的会话配置），并加 `--mixed-english`：用户看到的首屏带着混输的英文词（九键 63476 第 2 位的 Negro），关着它量不到。夹具的行按键盘分组，每种键盘写一份 `convert_eval` 的用例集再跑一次：九键的数字换成一串编码相同的字母（`convert_eval --grid nine` 自己再换回数字），14 键的组码原样交给 `--grid fourteen`。

用法（在仓库根目录）：

    python3 scripts/must_outrank.py run --resources <已校验的资源目录> [--resource-lock <锁>] \\
        [--binary target/release/examples/convert_eval] [--fixture resources/eval/must-outrank.tsv] \\
        [--out target/must-outrank] [--first-page-rows 6] [--json <结果.json>]

    python3 scripts/must_outrank.py check --dump full=<dump> --dump nine=<dump> [...] [--fixture ...] [--first-page-rows 6]

`check` 只读已有的 dump（`run` 写在 `--out` 下的 `<键盘>.jsonl`），换资源比较时不必重跑。任何一条失败都以退出码 1 结束，并逐条列出两个词的名次。
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import eval_keys

KINDS = ("outrank", "not-on-first-page")
KEYBOARDS = ("full", "nine", "fourteen")
COLUMNS = ["id", "kind", "keyboard", "input", "should_rank_higher", "should_rank_lower", "source"]
# 共享偏好的出厂每页候选数（`Preferences::default().candidate_page_size`），也是 `convert_eval` 不给 `--first-page-rows` 时的值。
DEFAULT_FIRST_PAGE_ROWS = 6


def load_fixture(path: Path) -> list:
    """读夹具并校验每一行：列数、kind、keyboard、输入能在这种键盘上打、来源不空、id 不重复。"""
    rows, seen = [], set()
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#") or line.startswith("id\t"):
            continue
        fields = line.split("\t")
        where = f"{path}:{number}"
        if len(fields) != len(COLUMNS):
            raise SystemExit(f"{where}: expected {len(COLUMNS)} columns ({', '.join(COLUMNS)}), got {len(fields)}")
        row = dict(zip(COLUMNS, fields))
        if row["id"] in seen:
            raise SystemExit(f"{where}: duplicate id {row['id']}")
        seen.add(row["id"])
        if row["kind"] not in KINDS:
            raise SystemExit(f"{where}: kind must be one of {', '.join(KINDS)}")
        if row["keyboard"] not in KEYBOARDS:
            raise SystemExit(f"{where}: keyboard must be one of {', '.join(KEYBOARDS)}")
        if not row["source"].strip():
            raise SystemExit(f"{where}: every row needs a source (feedback, issue or reviewed sample)")
        if row["should_rank_lower"] in ("", "-"):
            raise SystemExit(f"{where}: should_rank_lower is required")
        if row["kind"] == "outrank" and row["should_rank_higher"] in ("", "-"):
            raise SystemExit(f"{where}: outrank needs should_rank_higher")
        try:
            typed_letters(row)
        except ValueError as error:
            raise SystemExit(f"{where}: {error}") from error
        rows.append(row)
    if not rows:
        raise SystemExit(f"{path}: no rows")
    return rows


def typed_letters(row: dict) -> str:
    """交给 `convert_eval` 的字母输入。全键盘原样；九键把数字换成编码相同的字母；14 键的组码本身就是字母。"""
    text = row["input"]
    if row["keyboard"] == "nine":
        if not text.isdigit():
            raise ValueError(f"nine-key input must be digits, got {text}")
        return eval_keys.nine_digits_to_letters(text)
    if not text or any(not ("a" <= ch <= "z" or ch == "'") for ch in text):
        raise ValueError(f"{row['keyboard']} input must be lowercase letters (and '), got {text}")
    if row["keyboard"] == "fourteen" and eval_keys.encode("fourteen", text) != text.replace("'", ""):
        raise ValueError(f"fourteen-key input must be group codes ({''.join(sorted(set(eval_keys.FOURTEEN_KEYPAD)))}), got {text}")
    return text


def write_case_set(rows: list, path: Path) -> None:
    """一种键盘的用例集，格式同 `resources/eval/*.tsv`。金标准写应靠前的词（没有时写不该出现的词），只是让 `convert_eval` 的报告有东西可数，判定不看它。"""
    lines = ["# generated by scripts/must_outrank.py; do not commit", "id\tinput\tgold\tsyllables\ttags"]
    for row in rows:
        gold = row["should_rank_higher"] if row["should_rank_higher"] not in ("", "-") else row["should_rank_lower"]
        syllables = len(gold) if not gold.isascii() else 0
        lines.append(f"{row['id']}\t{typed_letters(row)}\t{gold}\t{syllables}\t{row['kind']}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def same_word(candidate: str, word: str) -> bool:
    """含汉字的词逐字相同；纯 ASCII 的英文词不分大小写。"""
    if word.isascii():
        return candidate.casefold() == word.casefold()
    return candidate == word


def rank_of(texts: list, word: str) -> int | None:
    for index, text in enumerate(texts):
        if same_word(text, word):
            return index + 1
    return None


def judge(row: dict, texts: list, first_page_rows: int) -> dict:
    """一行夹具在这张候选表上过没过，以及两个词各自的名次。"""
    higher = row["should_rank_higher"]
    has_higher = higher not in ("", "-")
    higher_rank = rank_of(texts, higher) if has_higher else None
    lower_rank = rank_of(texts, row["should_rank_lower"])
    if row["kind"] == "outrank":
        if higher_rank is None:
            passed, reason = False, f"{higher} is not in the candidates"
        elif lower_rank is not None and lower_rank < higher_rank:
            passed, reason = False, f"{row['should_rank_lower']} at {lower_rank} is above {higher} at {higher_rank}"
        else:
            passed, reason = True, ""
    else:
        if lower_rank is not None and lower_rank <= first_page_rows:
            passed, reason = False, f"{row['should_rank_lower']} is on the first page at {lower_rank}"
        elif has_higher and (higher_rank is None or higher_rank > first_page_rows):
            passed, reason = False, f"{higher} is not on the first page ({'absent' if higher_rank is None else higher_rank}); the input may be wrong"
        else:
            passed, reason = True, ""
    return {
        "id": row["id"],
        "kind": row["kind"],
        "keyboard": row["keyboard"],
        "input": row["input"],
        "should_rank_higher": higher,
        "should_rank_lower": row["should_rank_lower"],
        "higher_rank": higher_rank,
        "lower_rank": lower_rank,
        "passed": passed,
        "reason": reason,
        "first_page": texts[:first_page_rows],
        "source": row["source"],
    }


def check(rows: list, dumps: dict, first_page_rows: int) -> list:
    """按 id 在对应键盘的 dump 里找候选表并逐行判定。夹具有、dump 里没有的行直接报错：那是 dump 跑错了集合。"""
    results = []
    for row in rows:
        dump = dumps.get(row["keyboard"])
        if dump is None:
            raise SystemExit(f"{row['id']}: no dump for keyboard {row['keyboard']}")
        if row["id"] not in dump:
            raise SystemExit(f"{row['id']}: not in the {row['keyboard']} dump; it was run on another set")
        texts = [candidate["text"] for candidate in dump[row["id"]].get("candidates", [])]
        results.append(judge(row, texts, first_page_rows))
    return results


def print_results(results: list) -> int:
    failed = [result for result in results if not result["passed"]]
    for result in results:
        status = "PASS" if result["passed"] else "FAIL"
        ranks = f"higher={result['higher_rank'] or '-'} lower={result['lower_rank'] or '-'}"
        detail = f"  {result['reason']}; first page: {' '.join(result['first_page'])}" if not result["passed"] else ""
        claim = f"{result['should_rank_higher']} > {result['should_rank_lower']}" if result["kind"] == "outrank" else f"{result['should_rank_lower']} off the first page (anchor {result['should_rank_higher']})"
        print(f"{status} {result['id']} {result['keyboard']} {result['input']}: {claim} ({ranks}){detail}")
    print(f"must-outrank: {len(results) - len(failed)} of {len(results)} passed")
    return 1 if failed else 0


def main(argv: list | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    commands = parser.add_subparsers(dest="command", required=True)
    for name in ("run", "check"):
        command = commands.add_parser(name)
        command.add_argument("--fixture", type=Path, default=eval_keys.ROOT / "resources/eval/must-outrank.tsv")
        command.add_argument("--first-page-rows", type=int, default=DEFAULT_FIRST_PAGE_ROWS)
        command.add_argument("--json", type=Path, help="write every row's result here")
        if name == "run":
            command.add_argument("--resources", type=Path, required=True)
            command.add_argument("--resource-lock", type=Path)
            command.add_argument("--binary", type=Path, default=eval_keys.DEFAULT_BINARY)
            command.add_argument("--out", type=Path, default=eval_keys.ROOT / "target/must-outrank")
        else:
            command.add_argument("--dump", action="append", default=[], metavar="KEYBOARD=PATH", required=True)
    args = parser.parse_args(argv)
    rows = load_fixture(args.fixture)

    if args.command == "run":
        args.out.mkdir(parents=True, exist_ok=True)
        dumps = {}
        for keyboard in KEYBOARDS:
            subset = [row for row in rows if row["keyboard"] == keyboard]
            if not subset:
                continue
            case_set, dump = args.out / f"{keyboard}.tsv", args.out / f"{keyboard}.jsonl"
            write_case_set(subset, case_set)
            eval_keys.run_convert_eval(args.binary, args.resources.resolve(), args.resource_lock, case_set, dump, args.out / f"{keyboard}.report.json", keyboard,
                                       ["--mixed-english", "--first-page-rows", str(args.first_page_rows)])
            dumps[keyboard] = eval_keys.load_dump(dump)
    else:
        dumps = {}
        for item in args.dump:
            keyboard, _, path = item.partition("=")
            if keyboard not in KEYBOARDS or not path:
                raise SystemExit(f"--dump takes KEYBOARD=PATH with KEYBOARD one of {', '.join(KEYBOARDS)}")
            dumps[keyboard] = eval_keys.load_dump(Path(path))

    results = check(rows, dumps, args.first_page_rows)
    if args.json:
        args.json.write_text(json.dumps(results, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    return print_results(results)


if __name__ == "__main__":
    sys.exit(main())
